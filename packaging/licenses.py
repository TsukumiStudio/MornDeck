#!/usr/bin/env python3
"""THIRD_PARTY_LICENSES を作り直す。配るバイナリに入る crate (macOS 向けの通常の依存) の許諾文を、同じ文面ごとにまとめる。
--check を付けると、今のファイルと違えば 1 で終わる。"""
import glob, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD_PARTY_LICENSES")
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"]
NAMES = ["LICEN[SC]E*", "COPYING*", "NOTICE*", "UNLICENSE*", "COPYRIGHT*"]


def crates():
    """cargo tree が出す、実際にリンクされる crate だけ (cargo metadata は使わない optional の依存まで含む)"""
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ROOT))
    by_key = {f"{p['name']} v{p['version']}": p for p in meta["packages"]}
    root = by_key.pop(next(k for k, p in by_key.items() if p["id"] == meta["resolve"]["root"]))
    found = {}
    for target in TARGETS:
        tree = subprocess.check_output(
            ["cargo", "tree", "--locked", "--edges", "normal", "--target", target, "--prefix", "none", "--format", "{p}"], cwd=ROOT, text=True)
        for line in tree.splitlines():
            key = " ".join(line.split()[:2])
            if key and not key.startswith(root["name"] + " "):
                found[key] = by_key[key]
    return sorted(found.values(), key=lambda p: (p["name"], p["version"]))


def main():
    texts, bare = {}, []
    for p in crates():
        if not p.get("license"):
            sys.exit(f"license が無い: {p['name']} {p['version']}")
        label = f"{p['name']} {p['version']} ({p['license']})"
        d = os.path.dirname(p["manifest_path"])
        files = sorted({f for n in NAMES for f in glob.glob(os.path.join(d, n)) if os.path.isfile(f)})
        if not files:
            bare.append(f"{label} {p.get('repository') or ''}".rstrip())
        for f in files:
            text = open(f, encoding="utf-8", errors="replace").read().strip()
            texts.setdefault(text, []).append(label)
    out = ["Third-party software included in MornDeck, with license texts. Generated by packaging/licenses.py.", ""]
    for text, labels in sorted(texts.items(), key=lambda kv: kv[1]):
        out += ["=" * 78, *labels, "=" * 78, "", text, ""]
    # 標準ライブラリも静的に入る
    bare.append("Rust standard library (MIT OR Apache-2.0) https://github.com/rust-lang/rust")
    out += ["=" * 78, "Components that ship no license file (the text of the named license above applies)", "=" * 78, "", *bare, ""]
    body = "\n".join(out)
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != body:
            sys.exit("THIRD_PARTY_LICENSES が古い。python3 packaging/licenses.py で作り直す")
        return
    open(OUT, "w", encoding="utf-8").write(body)


main()
